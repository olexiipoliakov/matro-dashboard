"""
phone_key.py — один спосіб перетворити телефон на ключ зіставлення.

Навіщо окремий модуль. Ключ рахують два різні скрипти: fetch_bitrix.py (для
контактів угод) і fetch_ringostat.py (для номера, з якого дзвонили). Якщо
вони порахують по-різному, нічого не зламається явно — просто жодна угода не
зіставиться з жодним дзвінком, і модуль балів мовчки покаже нулі. Такий збій
шукати довго, тому функція живе в одному місці й імпортується обома.

Чому дев'ять цифр. Той самий український номер записаний як завгодно:
+380671234567, 380671234567, 0671234567, «067 123 45 67». Останні дев'ять
цифр збігаються в усіх варіантах і при цьому унікальні в межах країни.

Чому хеш, а не номер. bitrix_data.json лежить у публічному репозиторії.
Телефони клієнтів туди класти не можна — ні повні, ні обрізані. Для
зіставлення хеша цілком достатньо.
"""
import hashlib


def phone_key(raw):
    """Короткий хеш останніх 9 цифр номера. Порожній рядок, якщо цифр менше."""
    digits = "".join(ch for ch in str(raw or "") if ch.isdigit())
    if len(digits) < 9:
        return ""
    return hashlib.sha256(digits[-9:].encode()).hexdigest()[:12]
